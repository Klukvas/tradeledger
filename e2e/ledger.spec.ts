import { createAccount, createItem, expect, exportDocument, money, navigate, importHistoricalSnapshot, test } from './helpers'

test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Начните с текущих остатков' })).toBeVisible()
})

test('stock keeps exact value through receipts, issues and reload; invalid operations do not write', async ({ page, expectedApiErrors }) => {
  expectedApiErrors.push({ path: '/api/ledger/commands', status: 409 })
  await createItem(page)
  await page.getByRole('button', { name: 'Приход: Кабель', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Количество, шт.', { exact: true }).fill('2')
  await page.getByRole('dialog').getByLabel('Закупочная цена за единицу, UAH', { exact: true }).fill('20,02')
  await page.getByRole('dialog').getByRole('button', { name: 'Сохранить', exact: true }).click()
  const row = page.getByRole('row').filter({ hasText: 'SKU-01' })
  await expect(row.getByRole('cell').nth(1)).toHaveText('5')
  await expect(row.getByRole('cell').nth(2)).toHaveText(money(14.01))
  await expect(row.getByRole('cell').nth(3)).toHaveText(money(70.07))
  await page.getByRole('button', { name: 'Списать: Кабель', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Количество, шт.', { exact: true }).fill('6')
  await dialog.getByLabel('Причина списания', { exact: true }).fill('Продажа')
  await dialog.getByRole('button', { name: 'Списать', exact: true }).click()
  await expect(dialog.getByLabel('Количество, шт.', { exact: true })).toHaveAttribute('aria-invalid', 'true')
  await dialog.getByLabel('Количество, шт.', { exact: true }).fill('2')
  await dialog.getByRole('button', { name: 'Списать', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(row.getByRole('cell').nth(1)).toHaveText('3')
  await expect(row.getByRole('cell').nth(3)).toHaveText(money(42.04))
  await page.reload()
  await expect(row.getByRole('cell').nth(3)).toHaveText(money(42.04))
  await page.getByRole('button', { name: 'Добавить товар', exact: true }).click()
  await dialog.getByLabel('Артикул (SKU)', { exact: true }).fill(' sku-01 ')
  await dialog.getByLabel('Название товара', { exact: true }).fill('Дубликат')
  await dialog.getByLabel('Начальное количество, шт.', { exact: true }).fill('1')
  await dialog.getByLabel('Закупочная цена за единицу, UAH', { exact: true }).fill('5')
  await dialog.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await expect(dialog.getByRole('alert')).toBeVisible()
  await dialog.getByRole('button', { name: 'Отмена' }).click()
  const saved = await exportDocument(page)
  expect(saved.state.inventory).toHaveLength(1)
  expect(saved.state.inventory[0]).toMatchObject({ quantity: 3, stockValueMinor: 4204 })
  expect(saved.state.audit.map((entry) => entry.type)).toEqual(['inventory.create', 'inventory.receive', 'inventory.issue'])
})

test('MONO and NovaPay balances preserve imported legacy details without inventing a monthly baseline', async ({ page }) => {
  await createAccount(page, 'Основной MONO', '1000', 'MONO')
  await createAccount(page, 'Основной NovaPay', '250,50', 'NovaPay')
  await importHistoricalSnapshot(page, 'Начальный замер')
  await navigate(page, 'Счета')
  await page.getByRole('button', { name: 'Обновить баланс: Основной MONO, ФОП Тест', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Текущий баланс, UAH', { exact: true }).fill('1200')
  await page.getByRole('dialog').getByRole('button', { name: 'Сохранить', exact: true }).click()
  await page.getByRole('button', { name: 'Изменить данные: Основной MONO, ФОП Тест', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Название счёта', { exact: true }).fill('Переименован MONO')
  await page.getByRole('dialog').getByRole('button', { name: 'Сохранить', exact: true }).click()
  await navigate(page, 'Обзор')
  await expect(page.locator('.stat-card').filter({ hasText: 'Изменение денег' }).locator('.stat-value')).toHaveText('Нет данных за прошлый месяц')
  const baseline = page.getByRole('row').filter({ hasText: 'Начальный замер' })
  await baseline.locator('summary').click()
  await expect(baseline).toContainText('Основной MONO')
  await expect(baseline).not.toContainText('Переименован MONO')
  await expect(baseline.getByRole('listitem').filter({ hasText: 'Основной MONO' }).locator('.money')).toHaveText(money(1000))
  await importHistoricalSnapshot(page, 'Второй замер')
  const saved = await exportDocument(page)
  expect(saved.state.snapshots).toHaveLength(2)
  expect(saved.state.snapshots[0]).toMatchObject({ totalMinor: 125050 })
  expect(saved.state.snapshots[0]?.accounts[0]).toMatchObject({ name: 'Основной MONO', balanceMinor: 100000 })
  expect(saved.state.snapshots[1]).toMatchObject({ totalMinor: 145050 })
  await page.reload()
  await navigate(page, 'Обзор')
  await expect(page.locator('.stat-card').filter({ hasText: 'Изменение денег' }).locator('.stat-value')).toHaveText('Нет данных за прошлый месяц')
})

test('both debt directions support partial/full repayment and searchable closed history without bank changes', async ({ page }) => {
  await createAccount(page, 'Независимый счёт', '500')
  await navigate(page, 'Долги')
  for (const [direction, counterparty] of [['payable', 'Поставщик'], ['receivable', 'Клиент']] as const) {
    await page.getByRole('button', { name: 'Добавить долг', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByLabel('Направление долга', { exact: true }).selectOption(direction)
    await dialog.getByLabel('Контрагент', { exact: true }).fill(counterparty)
    await dialog.getByLabel('Сумма долга, UAH', { exact: true }).fill('100,50')
    await dialog.getByLabel('Примечание (необязательно)', { exact: true }).fill('Тестовый договор')
    await dialog.getByRole('button', { name: 'Сохранить', exact: true }).click()
    await page.getByRole('group', { name: 'Направление долгов' }).getByRole('button', { name: direction === 'payable' ? 'Я должен' : 'Мне должны', exact: true }).click()
    await page.getByRole('button', { name: 'Активные', exact: true }).click()
    await page.getByRole('button', { name: `Погасить: ${counterparty}`, exact: true }).click()
    await dialog.getByLabel('Сумма погашения, UAH', { exact: true }).fill('101')
    await dialog.getByRole('button', { name: 'Сохранить погашение' }).click()
    await expect(dialog.getByLabel('Сумма погашения, UAH', { exact: true })).toHaveAttribute('aria-invalid', 'true')
    await dialog.getByLabel('Сумма погашения, UAH', { exact: true }).fill('40,25')
    await dialog.getByRole('button', { name: 'Сохранить погашение' }).click()
    await expect(page.getByRole('row').filter({ hasText: counterparty }).getByRole('cell').nth(3)).toHaveText(money(60.25))
    await page.getByRole('button', { name: `Погасить: ${counterparty}`, exact: true }).click()
    await dialog.getByRole('button', { name: 'Всю оставшуюся сумму' }).click()
    await expect(dialog.getByLabel('Сумма погашения, UAH', { exact: true })).toHaveValue('60,25')
    await dialog.getByRole('button', { name: 'Сохранить погашение' }).click()
    await expect(page.getByRole('row').filter({ hasText: counterparty })).toHaveCount(0)
    await page.getByRole('button', { name: 'Закрытые', exact: true }).click()
    await page.getByLabel('Поиск по контрагенту или примечанию', { exact: true }).fill(counterparty)
    const row = page.getByRole('row').filter({ hasText: counterparty })
    await expect(row).toContainText('Закрыт')
    await expect(row.getByRole('button', { name: `Погасить: ${counterparty}`, exact: true })).toBeDisabled()
    await page.getByLabel('Поиск по контрагенту или примечанию', { exact: true }).fill('')
  }
  const saved = await exportDocument(page)
  expect(saved.state.accounts[0]?.balanceMinor).toBe(50000)
  expect(saved.state.debts.map((debt) => debt.repaidMinor)).toEqual([10050, 10050])
  expect(saved.state.audit.filter((entry) => entry.type === 'debt.repay')).toHaveLength(4)
})
