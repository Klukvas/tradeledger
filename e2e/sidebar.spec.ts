import { expect, navigate, test } from './helpers'

test('sidebar collapse, account controls and direct backup route stay usable', async ({ page, credentials }, info) => {
  const sidebar = page.getByRole('complementary', { name: 'Боковая панель' })
  const nav = page.getByRole('navigation', { name: 'Разделы учёта' })
  const toggle = page.getByRole('button', { name: 'Свернуть панель', exact: true })
  await expect(sidebar.locator('.sidebar-footer')).toHaveCount(0)
  await expect(sidebar.getByText('Данные хранятся на сервере.')).toHaveCount(0)
  await expect(nav.getByRole('link')).toHaveCount(5)
  await expect(nav.getByRole('link', { name: 'Резервная копия' })).toHaveCount(0)
  await expect(sidebar.getByRole('button', { name: 'Выйти', exact: true })).toBeVisible()
  await expect(sidebar.getByLabel(credentials.email, { exact: true })).toBeVisible()

  if (info.project.name === 'desktop') {
    for (const width of [1440, 1050, 1000, 761]) {
      await page.setViewportSize({ width, height: 1000 })
      const brand = sidebar.getByRole('link', { name: 'TradeLedger — обзор', exact: true })
      const brandBox = await brand.boundingBox()
      const markBox = await brand.locator('.brand-mark').boundingBox()
      const labelBox = await brand.locator('.sidebar-label').boundingBox()
      const toggleBox = await toggle.boundingBox()
      const navBox = await nav.boundingBox()
      if (!brandBox || !markBox || !labelBox || !toggleBox || !navBox) throw new Error('Sidebar header is not measurable')
      expect(toggleBox.width).toBeGreaterThanOrEqual(44)
      expect(toggleBox.height).toBeGreaterThanOrEqual(44)
      expect(Math.abs(markBox.y + markBox.height / 2 - toggleBox.y - toggleBox.height / 2)).toBeLessThan(1)
      expect(brandBox.x + brandBox.width).toBeLessThanOrEqual(toggleBox.x)
      expect(labelBox.x + labelBox.width).toBeLessThanOrEqual(toggleBox.x)
      expect(navBox.y).toBeLessThan(130)
      expect((await sidebar.boundingBox())?.width).toBe(width > 1050 ? 232 : 196)
      await expect(toggle).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)')
      await expect(toggle).toHaveCSS('border-top-width', '0px')
      await expect(toggle.locator('svg')).toHaveAttribute('width', '18')
      await expect(sidebar.locator('.brand-subtitle')).toBeVisible()
      await page.screenshot({ path: `.cache/compact-toggle/expanded-${width}.png` })
    }
    for (const height of [600, 768]) {
      await page.setViewportSize({ width: 1366, height })
      const logout = sidebar.getByRole('button', { name: 'Выйти', exact: true })
      await logout.scrollIntoViewIfNeeded()
      await logout.focus()
      const box = await logout.boundingBox()
      expect(box?.y).toBeGreaterThanOrEqual(0)
      expect((box?.y ?? 0) + (box?.height ?? 0)).toBeLessThanOrEqual(height)
      await expect(logout).toBeFocused()
      await page.screenshot({ path: `.cache/compact-toggle/short-${height}.png` })
    }
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.evaluate(() => window.scrollTo(0, 0))
    await expect(toggle).toHaveAttribute('aria-expanded', 'true')
    const toggleBox = await toggle.boundingBox()
    expect(toggleBox?.width).toBeGreaterThanOrEqual(44)
    expect(toggleBox?.height).toBeGreaterThanOrEqual(44)
    expect((await sidebar.boundingBox())?.width).toBe(232)
    await page.screenshot({ path: '.cache/compact-toggle/expanded.png', fullPage: true })
    await toggle.focus()
    await page.keyboard.press('Shift+Tab')
    await page.keyboard.press('Tab')
    await expect(toggle).toBeFocused()
    await expect(toggle.locator('.sidebar-tooltip')).toBeVisible()
    await page.screenshot({ path: '.cache/compact-toggle/toggle-focus.png' })
    await page.keyboard.press('Enter')
    const expand = page.getByRole('button', { name: 'Развернуть панель', exact: true })
    await expect(expand).toBeFocused()
    await expect(expand).toHaveAttribute('aria-expanded', 'false')
    await page.screenshot({ path: '.cache/compact-toggle/toggle-collapsed.png' })
    expect((await sidebar.boundingBox())?.width).toBe(76)
    const collapsedBrand = await sidebar.locator('.brand-mark').boundingBox()
    const expandBox = await expand.boundingBox()
    if (!collapsedBrand || !expandBox) throw new Error('Collapsed sidebar header is not measurable')
    expect(Math.abs(collapsedBrand.x + collapsedBrand.width / 2 - expandBox.x - expandBox.width / 2)).toBeLessThan(1)
    expect(collapsedBrand.y + collapsedBrand.height).toBeLessThanOrEqual(expandBox.y)
    for (const link of await nav.getByRole('link').all()) {
      await expect(link.locator('.sidebar-label')).not.toBeVisible()
      await link.focus()
      await expect(link.locator('.sidebar-tooltip')).toBeVisible()
      const box = await link.boundingBox()
      expect(box?.width).toBeGreaterThanOrEqual(44)
      expect(box?.height).toBeGreaterThanOrEqual(44)
    }
    await sidebar.getByLabel(credentials.email, { exact: true }).focus()
    await expect(sidebar.locator('.account-email .sidebar-tooltip')).toBeVisible()
    await page.screenshot({ path: '.cache/compact-toggle/collapsed.png', fullPage: true })
    await navigate(page, 'История')
    await expect(nav.getByRole('link', { name: 'История', exact: true })).toHaveAttribute('aria-current', 'page')
    await page.reload()
    await expect(expand).toHaveAttribute('aria-expanded', 'false')
    await page.setViewportSize({ width: 1000, height: 1000 })
    expect((await sidebar.boundingBox())?.width).toBe(76)
    await expand.click()
    expect((await sidebar.boundingBox())?.width).toBe(196)
    await page.getByRole('button', { name: 'Свернуть панель' }).click()
  }

  for (const width of [320, 390, 760]) {
    await page.setViewportSize({ width, height: 844 })
    await expect(page.locator('.sidebar-toggle')).not.toBeVisible()
    await expect(nav.getByRole('link', { name: 'История', exact: true }).locator('.sidebar-label')).toBeVisible()
    await expect(sidebar.getByRole('button', { name: 'Выйти', exact: true })).toBeVisible()
    await expect(sidebar.locator('.account-email .sidebar-label')).toBeVisible()
    await expect(sidebar.locator('.brand-subtitle')).not.toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: `.cache/compact-toggle/mobile-${info.project.name}-${width}.png` })
  }
  if (info.project.name === 'mobile') {
    await page.setViewportSize({ width: 390, height: 844 })
    await page.screenshot({ path: '.cache/compact-toggle/mobile.png' })
  }
  await navigate(page, 'Резервная копия')
  await expect(page).toHaveTitle('Резервная копия · TradeLedger')
  await page.getByRole('button', { name: 'Выйти', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Вход в TradeLedger', exact: true })).toBeVisible()
})
